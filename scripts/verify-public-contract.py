def php_array_keys(source: str, marker: str) -> set[str]:
    start = source.find(marker)
    if start < 0:
        fail(f"Missing server projection marker: {marker}")
    return set(re.findall(r"'([a-z][a-z0-9_]*)'\s*=>", source[start : start + 5000]))


def object_fields(contract: dict[str, object], name: str) -> list[str]:
    definitions = contract.get("$defs")
    if not isinstance(definitions, dict):
        fail("The canonical public contract definitions are missing.")
    definition = definitions.get(name)
    if not isinstance(definition, dict) or definition.get("type") != "object" \
            or definition.get("additionalProperties") is not False:
        fail(f"The canonical object definition is not closed: {name}.")
    properties = definition.get("properties")
    required = definition.get("required")
    if not isinstance(properties, dict) or not isinstance(required, list) \
            or not set(required).issubset(properties):
        fail(f"The canonical object definition is incomplete: {name}.")
    return list(properties)


